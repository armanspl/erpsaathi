    <h2>What data we process</h2>
    <p>
        Each school using ERPSaathi controls its own data — student records, staff records, attendance,
        fee and academic information are entered and managed by that school's authorized staff. This
        data is stored in a database dedicated to that school and is not shared with other schools.
    </p>

    <h2>How data is protected</h2>
    <ul>
        <li>Access to school data requires authenticated, role-based login.</li>
        <li>Create, update and delete actions are recorded in an audit log.</li>
        <li>Each school's records are kept in a centralized, access-controlled database.</li>
    </ul>

